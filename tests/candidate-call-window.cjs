const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync('public/js/candidate-calls.js','utf8');
const helper=source.slice(source.indexOf('    function initCallWindow'),source.indexOf('    function init(root)'));
const classes=new Set(), handlers={};
const panel={style:{},getBoundingClientRect(){return {left:100,top:100,width:classes.has('call-minimized')?300:390,height:classes.has('call-minimized')?220:550};}};
const handle={addEventListener(n,fn){handlers[n]=fn;},setPointerCapture(){}};
const toggle={addEventListener(n,fn){this.click=fn;},setAttribute(n,v){this[n]=v;}};
const root={isConnected:true,classList:{add(v){classes.add(v);},toggle(v,on){if(on)classes.add(v);else classes.delete(v);}},setAttribute(n,v){this[n]=v;},querySelector(s){return {'#call-panel':panel,'#call-drag-handle':handle,'#call-minimize':toggle}[s];}};
const window={innerWidth:1000,innerHeight:800,addEventListener(){}};
vm.runInNewContext(helper+';initCallWindow(root);',{root,window});
toggle.click();
assert.ok(classes.has('call-minimized'));
assert.equal(root['aria-modal'],'false');
assert.equal(toggle['aria-expanded'],'false');
assert.equal(panel.style.left,'680px');
root._restoreCallWindow();
assert.ok(!classes.has('call-minimized'));
assert.equal(toggle['aria-expanded'],'true');
handlers.pointerdown({button:0,isPrimary:true,pointerId:1,clientX:110,clientY:110,preventDefault(){}});
handlers.pointermove({pointerId:1,clientX:-100,clientY:2000});
assert.equal(panel.style.left,'8px');
assert.equal(panel.style.top,'242px');
handlers.pointerup();
handlers.pointermove({pointerId:1,clientX:500,clientY:500});
assert.equal(panel.style.left,'8px');
console.log('PASS: minimize, restore, dragging and viewport bounds without call lifecycle changes');
